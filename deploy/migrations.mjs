import { readFile, readdir } from "node:fs/promises";
import { createHash } from "node:crypto";
import { resolve } from "node:path";
import { fileURLToPath } from "node:url";
export const sqlQuote = (value) => `'${String(value).replaceAll("'", "''")}'`;
export function stripTransaction(sql) {
  // Repository migrations have optional outer BEGIN/COMMIT. Never rewrite function bodies.
  const starts = [...sql.matchAll(/^begin;\s*$/gim)],
    ends = [...sql.matchAll(/^commit;\s*$/gim)];
  if (starts.length !== ends.length || starts.length > 1)
    throw new Error("Unsupported migration transaction layout");
  return sql.replace(/^begin;\s*$/gim, "").replace(/^commit;\s*$/gim, "");
}
export async function loadMigrations(directory) {
  if (directory instanceof URL) directory = fileURLToPath(directory);
  const files = (await readdir(directory))
    .filter((n) => /^\d{14}_[a-z0-9_]+\.sql$/.test(n))
    .sort();
  if (!files.length) throw new Error("No migrations found");
  const rows = await Promise.all(
    files.map(async (file) => {
      const source = (
        await readFile(resolve(directory, file), "utf8")
      ).replaceAll("\r\n", "\n");
      return {
        version: file.slice(0, 14),
        file,
        checksum: createHash("sha256").update(source).digest("hex"),
        sql: stripTransaction(source),
      };
    }),
  );
  if (new Set(rows.map((r) => r.version)).size !== rows.length)
    throw new Error("Duplicate migration version");
  return rows;
}
export function migrationPlan(rows, mode = "apply") {
  if (!["apply", "baseline-cloud"].includes(mode))
    throw new Error("Invalid migration mode");
  const versions = rows.map((r) => sqlQuote(r.version)).join(",");
  const header = `\\set ON_ERROR_STOP on
BEGIN;
SELECT pg_advisory_xact_lock(819240, 1);
CREATE SCHEMA IF NOT EXISTS _matchsho_deploy;
REVOKE ALL ON SCHEMA _matchsho_deploy FROM PUBLIC, anon, authenticated;
CREATE TABLE IF NOT EXISTS _matchsho_deploy.migrations(version text PRIMARY KEY, checksum text NOT NULL, applied_at timestamptz NOT NULL DEFAULT now());
REVOKE ALL ON _matchsho_deploy.migrations FROM PUBLIC, anon, authenticated;
DO $guard$ BEGIN
IF EXISTS(SELECT 1 FROM _matchsho_deploy.migrations WHERE version NOT IN (${versions})) THEN RAISE EXCEPTION 'Database has migrations missing from this checkout; use the correct release'; END IF;
${
  mode === "baseline-cloud"
    ? `IF to_regclass('public.bookings') IS NULL OR to_regclass('supabase_migrations.schema_migrations') IS NULL THEN RAISE EXCEPTION 'Restore database AND Cloud migration history before baselining'; END IF;
IF EXISTS(SELECT 1 FROM supabase_migrations.schema_migrations WHERE version NOT IN (${versions})) OR (SELECT count(DISTINCT version) FROM supabase_migrations.schema_migrations WHERE version IN (${versions})) <> ${rows.length} THEN RAISE EXCEPTION 'Cloud history does not match this release; do not mark unapplied migrations as applied'; END IF;`
    : `IF to_regclass('public.admins') IS NOT NULL AND NOT EXISTS(SELECT 1 FROM _matchsho_deploy.migrations) THEN RAISE EXCEPTION 'Existing app database without deployment history: restore Cloud history and run baseline-cloud, never replay migrations'; END IF;`
}
END $guard$;`;
  return `${header}\n${rows
    .map((r) => {
      if (!/^\d{14}$/.test(r.version) || !/^[a-f0-9]{64}$/.test(r.checksum))
        throw new Error("Invalid migration identity");
      const tag = `$migration_${r.version}$`;
      if (r.sql.includes(tag)) throw new Error("Migration delimiter collision");
      return `DO $step$ DECLARE saved text; BEGIN
SELECT checksum INTO saved FROM _matchsho_deploy.migrations WHERE version=${sqlQuote(r.version)};
IF saved IS NOT NULL AND saved <> ${sqlQuote(r.checksum)} THEN RAISE EXCEPTION 'Applied migration changed: ${r.version}'; END IF;
IF saved IS NULL THEN
${mode === "apply" ? `EXECUTE ${tag}${r.sql}${tag};` : "-- Verified Cloud baseline: do not execute historical SQL."}
INSERT INTO _matchsho_deploy.migrations(version,checksum) VALUES(${sqlQuote(r.version)},${sqlQuote(r.checksum)});
END IF; END $step$;`;
    })
    .join("\n")}\nNOTIFY pgrst, 'reload schema';\nCOMMIT;\n`;
}
export function jobsPlan(token) {
  if (!/^[a-f0-9]{64}$/.test(token ?? ""))
    throw new Error("Set the private CALENDAR_WORKER_TOKEN generated by setup");
  return `\\set ON_ERROR_STOP on
BEGIN;
DO $jobs$ DECLARE sid uuid; BEGIN
IF to_regclass('vault.secrets') IS NULL OR to_regclass('cron.job') IS NULL THEN RAISE EXCEPTION 'Vault and pg_cron must be available'; END IF;
IF NOT EXISTS(SELECT 1 FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace WHERE n.nspname='net' AND p.proname='http_post') THEN RAISE EXCEPTION 'Enable pg_net before configuring calendar jobs'; END IF;
SELECT id INTO sid FROM vault.secrets WHERE name='calendar_worker_token';
IF sid IS NULL THEN PERFORM vault.create_secret(${sqlQuote(token)},'calendar_worker_token'); ELSE PERFORM vault.update_secret(sid,${sqlQuote(token)}); END IF;
SELECT id INTO sid FROM vault.secrets WHERE name='calendar_worker_url';
IF sid IS NULL THEN PERFORM vault.create_secret('http://api-gw:8000/functions/v1/calendar-sync','calendar_worker_url'); ELSE PERFORM vault.update_secret(sid,'http://api-gw:8000/functions/v1/calendar-sync'); END IF;
PERFORM cron.schedule('rallyyar-calendar-sync','* * * * *','select private.dispatch_calendar_sync();');
PERFORM cron.schedule('padel-expiry','* * * * *','select public.expire_booking_proposals(); select public.run_platform_jobs();');
END $jobs$;
COMMIT;\n`;
}
if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  const mode = process.argv[2] ?? "apply";
  if (mode === "jobs")
    process.stdout.write(jobsPlan(process.env.CALENDAR_WORKER_TOKEN));
  else
    process.stdout.write(
      migrationPlan(
        await loadMigrations(
          fileURLToPath(new URL("../supabase/migrations/", import.meta.url)),
        ),
        mode,
      ),
    );
}
